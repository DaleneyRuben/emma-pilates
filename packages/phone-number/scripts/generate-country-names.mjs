// Writes src/generated/country-names.ts: every country libphonenumber-js
// knows, with its Spanish name from Node's ICU, A–Z as a Spanish reader sorts
// them. Run it after upgrading libphonenumber-js (the package's spec fails
// when a country is missing): `pnpm --filter @pilates/phone-number generate:countries`.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { getCountries } = require("libphonenumber-js/max");

const names = new Intl.DisplayNames(["es"], { type: "region" });
const rows = getCountries()
  .map((iso) => [iso, names.of(iso)])
  .sort(([, a], [, b]) => a.localeCompare(b, "es"));

const lines = [
  "// Generated by scripts/generate-country-names.mjs from libphonenumber-js",
  "// and Node's ICU Spanish region names. Do not edit by hand.",
  "export const countryNames: readonly (readonly [iso: string, name: string])[] = [",
  ...rows.map(([iso, name]) => `  [${JSON.stringify(iso)}, ${JSON.stringify(name)}],`),
  "];",
  "",
];
writeFileSync(new URL("../src/generated/country-names.ts", import.meta.url), lines.join("\n"));
console.log(`${rows.length} countries`);
